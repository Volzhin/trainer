/**
 * Сжатие ролика техники на устройстве, до отправки.
 *
 * Зачем вообще. Телефон снимает 1080p60 примерно по 130 МБ на минуту, и
 * ровно столько уезжало тренеру: сорокапятисекундный подход весил 92 МБ и
 * шёл по честным мобильным 2 Мбит/с шесть минут. Тренеру же нужна форма
 * движения, а не разрешение — 720p хватает, чтобы увидеть колено и спину.
 * После пережатия тот же подход весит 8 МБ и уходит за полминуты.
 *
 * Почему на устройстве, а не на сервере. Перекодирование на сервере не
 * спасает ни от одного из двух зол: байты всё равно проехали по мобильной
 * сети клиента, а ffmpeg на машине, где живёт ещё и чужой проект, — худшее,
 * что там можно запустить. Здесь же кодирует аппаратный кодек телефона, и
 * сервер об этом ничего не знает.
 *
 * Почему без Web Worker. Замеряли: сжатие в главном потоке не держит его —
 * WebCodecs кодирует вне JS, а на долю потока остаётся разбор контейнера.
 * Худшая заминка не отличалась от воркера. Воркер добавил бы протокол
 * сообщений и отдельную сборку, не покупая ничего.
 */

/*
 * 720p/30 при 1,5 Мбит — с запасом для зала: там статичный кадр и один
 * движущийся человек, то есть самый лёгкий для кодека случай.
 */
const HEIGHT = 720
const FPS = 30
const BITRATE = 1_500_000

/**
 * Ролик длиннее этого не сжимаем целиком, а обрезаем.
 *
 * Подход столько не длится: пять минут — это уже снятая целиком тренировка,
 * то есть промах. Обрезать лучше, чем сжимать двадцать минут и получить
 * файл, который никто не станет смотреть. Держим с запасом к реальному
 * подходу, чтобы не отрезать заход и отход от снаряда.
 */
const MAX_SECONDS = 180

/** Мельче этого пережимать нечего: выигрыш не окупит ожидания. */
const SKIP_UNDER = 6 * 1024 * 1024

export type ShrinkProgress = (fraction: number) => void

/** Умеет ли устройство кодировать видео силами браузера. */
export function canShrink(): boolean {
  return typeof VideoEncoder !== 'undefined' && typeof VideoDecoder !== 'undefined'
}

/**
 * Пережимает ролик под просмотр тренером.
 *
 * Возвращает исходный файл, если сжать не вышло или незачем: не видео,
 * старый браузер без WebCodecs, файл и так лёгкий, кодек отказался. Отказ
 * здесь — не ошибка прикрепления: ролик у человека уже снят, и потерять его
 * из-за неудачного пережатия было бы худшим исходом, чем отправить тяжёлым.
 */
export async function shrinkVideo(file: File, onProgress?: ShrinkProgress): Promise<File> {
  if (!file.type.startsWith('video/') || file.size < SKIP_UNDER || !canShrink()) return file

  try {
    /*
     * Грузим кодировщик отдельным куском и только здесь: он весит заметно
     * больше самого приложения, а нужен лишь тому, кто прикрепляет видео.
     */
    const {
      ALL_FORMATS,
      BlobSource,
      BufferTarget,
      Conversion,
      Input,
      Mp4OutputFormat,
      Output,
    } = await import('mediabunny')

    /*
     * ALL_FORMATS, а не список из mp4/QuickTime/webm.
     *
     * Список выглядит бережливее, но это иллюзия: пробовали — собранный кусок
     * получается побайтово тем же, демуксеры не отсеиваются сборщиком. Раз
     * платить всё равно приходится за все, пусть открывается и то, что снял
     * незнакомый нам телефон, а не только четыре ожидаемых контейнера.
     */
    const input = new Input({ source: new BlobSource(file), formats: ALL_FORMATS })
    const output = new Output({
      // moov в начале файла: тренер начинает смотреть с первых килобайт,
      // не дожидаясь всего ролика.
      format: new Mp4OutputFormat({ fastStart: 'in-memory' }),
      target: new BufferTarget(),
    })

    /*
     * Длительность берём из заголовка, а не пересчётом по пакетам:
     * computeDuration() ради этого читает файл целиком, то есть удваивает
     * работу над стомегабайтным роликом ради одного числа. Нет в заголовке —
     * считаем, что укладываемся, и не обрезаем.
     */
    const duration = (await input.getDurationFromMetadata().catch(() => null)) ?? 0
    const conversion = await Conversion.init({
      input,
      output,
      // fit: 'contain' — не режем кадр: вертикальное видео из зала обычное
      // дело, и обрезка по ширине отрезала бы как раз человека.
      video: { height: HEIGHT, frameRate: FPS, codec: 'avc', bitrate: BITRATE, fit: 'contain' },
      // Звук оставляем: тренер иногда проговаривает счёт вслух. Моно и
      // 64 кбит — на фоне видео это уже незаметная доля веса.
      audio: { codec: 'aac', bitrate: 64_000 },
      ...(duration > MAX_SECONDS ? { trim: { start: 0, end: MAX_SECONDS } } : {}),
    })
    if (!conversion.isValid) return file
    if (onProgress) conversion.onProgress = (p) => onProgress(p)
    await conversion.execute()

    const buffer = output.target.buffer
    if (!buffer) return file
    const blob = new Blob([buffer], { type: 'video/mp4' })

    // Бывает, что пережатый файл тяжелее исходного: короткий ролик, уже
    // сжатый сильнее нашего пресета. Тогда наша работа только навредила.
    if (blob.size >= file.size) return file

    return new File([blob], file.name.replace(/\.[^.]+$/, '') + '.mp4', {
      type: 'video/mp4',
      lastModified: file.lastModified,
    })
  } catch {
    /* Кодек отказал или кончилась память — отправляем как сняли. */
    return file
  }
}
