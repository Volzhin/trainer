import type { ConsentKind } from '../db/db'

/**
 * Тексты оферты и согласия на обработку персональных данных.
 *
 * Текст один на всё приложение, а не свой у каждого тренера: условия
 * работы задаёт сервис, тренер к ним присоединяется так же, как клиент.
 *
 * ВЕРСИЯ МЕНЯЕТСЯ ПРИ КАЖДОЙ ПРАВКЕ ТЕКСТА. Подпись хранится вместе с
 * версией (см. Consent в db.ts), потому что согласие «когда-то вообще»
 * юридически не значит ничего: нужно знать, под чем именно подписались.
 * Старые подписи при этом не аннулируются — человек соглашался с той
 * редакцией, которая была ему показана.
 */

export type ConsentDoc = {
  kind: ConsentKind
  /** Заголовок в списке и в шапке текста. */
  title: string
  /** Строка над галочкой — то, что человек читает, если не открыл текст. */
  summary: string
  version: string
  body: string
}

/**
 * Заглушка до передачи готовых текстов. Показывать это живым клиентам
 * нельзя — см. PLACEHOLDER ниже, интерфейс предупреждает об этом сам.
 */
export const CONSENTS_ARE_PLACEHOLDER = true

export const CONSENT_DOCS: ConsentDoc[] = [
  {
    kind: 'offer',
    title: 'Оферта',
    summary: 'Условия работы с тренером через приложение',
    version: '0-draft',
    body: `Здесь будет текст оферты.

Документ описывает, на каких условиях тренер и клиент работают через
приложение: что входит в услугу, как она оплачивается, как стороны
прекращают работу.

Текст предоставляет владелец сервиса. До этого момента редакция считается
черновиком, а подписи под ней — техническими.`,
  },
  {
    kind: 'personal_data',
    title: 'Согласие на обработку персональных данных',
    summary: 'Какие данные собираются и зачем',
    version: '0-draft',
    body: `Здесь будет текст согласия на обработку персональных данных.

Документ описывает, какие данные приложение собирает (имя, рост, вес,
замеры, тренировки, питание), кто получает к ним доступ (вы и ваш тренер),
сколько они хранятся и как их удалить.

Текст предоставляет владелец сервиса. До этого момента редакция считается
черновиком, а подписи под ней — техническими.`,
  },
]

export const consentDoc = (kind: ConsentKind): ConsentDoc =>
  CONSENT_DOCS.find((d) => d.kind === kind) ?? CONSENT_DOCS[0]

/** Подписи под текущими редакциями — то, что нужно собрать при привязке. */
export const currentConsents = () =>
  CONSENT_DOCS.map((d) => ({ kind: d.kind, version: d.version }))
